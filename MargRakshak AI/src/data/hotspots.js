/**
 * Validate and normalize a hotspot object from any data source (API, GeoJSON, CSV, or fallback).
 * Ensures valid numeric lat/lng and standard properties to prevent map crashes.
 */
export function normalizeHotspot(h) {
  let lat = h.lat ?? h.latitude;
  let lng = h.lng ?? h.longitude;
  lat = parseFloat(lat);
  lng = parseFloat(lng);

  // Fix known coordinate decimal shift if encountered
  if (lat > 9 && lat < 11) lat = lat + 10;

  // Validate coordinates
  const isValidLat = typeof lat === 'number' && !isNaN(lat) && lat >= -90 && lat <= 90;
  const isValidLng = typeof lng === 'number' && !isNaN(lng) && lng >= -180 && lng <= 180;

  if (!isValidLat || !isValidLng) {
    console.warn(`[Hotspot Data Validation] Invalid coordinates for hotspot "${h.name}": `, { lat, lng });
  }

  const riskLevel = String(h.riskLevel || h.risk_level || 'MEDIUM').toUpperCase();
  const riskScore = typeof h.riskScore === 'number' 
    ? h.riskScore 
    : (typeof h.risk_score === 'number' ? h.risk_score : 0.6);

  const accidentCount = h.accidentCount ?? h.accident_count ?? 0;
  const fatalities = h.fatalities ?? 0;
  const injuries = h.injuries ?? Math.max(0, accidentCount - fatalities);
  const density = typeof h.density === 'number' ? h.density : Math.round((accidentCount / 3) * 10) / 10;

  return {
    ...h,
    id: h.id ?? Math.floor(Math.random() * 100000),
    name: h.name || 'Unnamed Blackspot',
    lat: isValidLat ? lat : 19.9975,
    lng: isValidLng ? lng : 73.7898,
    latitude: isValidLat ? lat : 19.9975,
    longitude: isValidLng ? lng : 73.7898,
    isValid: isValidLat && isValidLng,
    policeStation: h.policeStation || h.police_station || '',
    police_station: h.policeStation || h.police_station || '',
    roadClass: h.roadClass || h.road_class || 'City Road',
    road_class: h.roadClass || h.road_class || 'City Road',
    roadNo: h.roadNo || h.road_no || '',
    road_no: h.roadNo || h.road_no || '',
    riskLevel,
    risk_level: riskLevel,
    riskScore,
    risk_score: riskScore,
    accidentCount,
    accident_count: accidentCount,
    fatalities,
    injuries,
    peakTime: h.peakTime || h.peak_time || 'All Times',
    peak_time: h.peakTime || h.peak_time || 'All Times',
    peakDay: h.peakDay || h.peak_day || 'All Days',
    peak_day: h.peakDay || h.peak_day || 'All Days',
    season: h.season || 'All Seasons',
    collisionType: h.collisionType || h.collision_type || 'Vehicle Collision',
    collision_type: h.collisionType || h.collision_type || 'Vehicle Collision',
    speedLimit: h.speedLimit || h.speed_limit || 40,
    speed_limit: h.speedLimit || h.speed_limit || 40,
    safetyRecommendation: h.safetyRecommendation || h.safety_recommendation || 'Drive carefully in this high accident zone.',
    safety_recommendation: h.safetyRecommendation || h.safety_recommendation || 'Drive carefully in this high accident zone.',
    riskFactors: Array.isArray(h.riskFactors) ? h.riskFactors : (Array.isArray(h.risk_factors) ? h.risk_factors : ['High Traffic Zone']),
    risk_factors: Array.isArray(h.riskFactors) ? h.riskFactors : (Array.isArray(h.risk_factors) ? h.risk_factors : ['High Traffic Zone']),
    radius: h.radius ?? h.radius_meters ?? 200,
    radius_meters: h.radius ?? h.radius_meters ?? 200,
    density,
    algorithm: h.algorithm || 'HDBSCAN / Traffic Police',
    source: h.source || 'Unified Nashik Traffic Blackspot Database',
    lastUpdated: h.lastUpdated || h.last_updated || '2026-09-21',
    last_updated: h.lastUpdated || h.last_updated || '2026-09-21',
  };
}

/**
 * Get normalized fallback mock hotspots when backend is unreachable or empty.
 * Returns all 102 blackspot locations with standardized properties and validated coordinates.
 */
export function getFallbackHotspots() {
  return mockHotspots
    .map(normalizeHotspot)
    .filter((spot) => spot.isValid);
}

/**
 * Get GeoJSON FeatureCollection format for Leaflet/AdminMap.
 * Returns standard RFC 7946 GeoJSON FeatureCollection.
 */
export function getFallbackHotspotsGeoJSON() {
  const normalizedList = getFallbackHotspots();
  return {
    type: 'FeatureCollection',
    features: normalizedList.map((h) => ({
      type: 'Feature',
      geometry: {
        type: 'Point',
        coordinates: [h.lng, h.lat],
      },
      properties: {
        ...h,
      },
    })),
  };
}
